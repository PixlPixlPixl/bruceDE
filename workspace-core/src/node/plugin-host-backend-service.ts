import { promises as fs } from 'fs';
import * as path from 'path';
import type express = require('@theia/core/shared/express');
import { inject, injectable } from '@theia/core/shared/inversify';
import {
    type BackendApplicationContribution,
    BackendApplicationPath
} from '@theia/core/lib/node/backend-application';
import { ILogger } from '@theia/core/lib/common/logger';
import {
    HOST_MODULE_PREFIX,
    PLUGIN_ASSET_PREFIX,
    type PluginHostClient,
    type PluginHostSnapshot,
    type PluginDiagnostic
} from '../common/plugin-host-protocol.js';
import { discoverPlugins, isUserPluginPath, toDescriptor, type DiscoveredPlugin } from './plugin-discovery.js';
import { resolvePluginRoots } from './plugin-paths.js';
import { PluginStateStore } from './plugin-state-store.js';
import { PluginBackendRuntime } from './plugin-backend-runtime.js';
import type { PluginServiceRegistry } from '../common/plugin-registries.js';

const CONTENT_TYPES: Readonly<Record<string, string>> = {
    '.js': 'text/javascript; charset=utf-8',
    '.mjs': 'text/javascript; charset=utf-8',
    '.cjs': 'text/javascript; charset=utf-8',
    '.json': 'application/json; charset=utf-8',
    '.css': 'text/css; charset=utf-8',
    '.map': 'application/json; charset=utf-8',
    '.svg': 'image/svg+xml',
    '.png': 'image/png',
    '.woff': 'font/woff',
    '.woff2': 'font/woff2'
};

/**
 * Backend half of the plugin host.
 *
 * Owns discovery, persisted trust/enable decisions, the served ESM bundles and
 * the backend plugin runtime. The renderer talks to it exclusively through
 * {@link PluginHostClient}; no filesystem path crosses that boundary except in
 * the diagnostic `directory` field.
 */
@injectable()
export class PluginHostBackendService implements BackendApplicationContribution, PluginHostClient {
    protected readonly roots: string[] = [];
    protected discovered: readonly DiscoveredPlugin[] = [];
    protected diagnostics: readonly PluginDiagnostic[] = [];
    protected readonly state = new PluginStateStore();
    protected readonly runtime: PluginBackendRuntime;
    protected ready: Promise<void> | undefined;

    constructor(@inject(ILogger) protected readonly logger: ILogger) {
        this.runtime = new PluginBackendRuntime({
            isTrusted: pluginId => this.isTrusted(pluginId),
            logger: {
                info: message => this.logger.info(message),
                error: message => this.logger.error(message)
            }
        });
    }

    /** Shared backend service registry, used by the RPC service bridge. */
    get backendServices(): PluginServiceRegistry {
        return this.runtime.services;
    }

    /** Service ids currently provided by backend plugins. */
    backendServiceIds(): readonly string[] {
        return this.runtime.services.ids();
    }

    /**
     * Mounts the plugin asset route and activates already-enabled backend
     * plugins. Idempotent: Theia may call this from the contribution lifecycle
     * while an RPC arrives before that point.
     */
    async initialize(): Promise<void> {
        if (this.ready) {
            await this.ready;
            return;
        }
        this.ready = this.start();
        await this.ready;
    }

    protected async start(): Promise<void> {
        this.roots.length = 0;
        this.roots.push(...(await resolvePluginRoots(BackendApplicationPath)));
        await this.rescan();
        this.logger.info(
            `[plugin-host] Discovered ${this.discovered.length} plugin(s) in ${this.roots.length} root(s).`
        );
        await this.activateEnabledBackendPlugins();
    }

    configure(app: express.Application): void {
        app.use(`${PLUGIN_ASSET_PREFIX}/:pluginId`, (request: express.Request, response: express.Response) => {
            void this.serveAsset(request, response);
        });
        // Host-module shims are generated by the renderer. Asking the backend for
        // one is a programming error, but answer clearly instead of 404-ing.
        app.use(`${HOST_MODULE_PREFIX}/:file`, (_request: express.Request, response: express.Response) => {
            response.status(404).type('text/plain').send('Host modules are resolved in the renderer.');
        });
    }

    async readFrontendBundle(pluginId: string): Promise<string> {
        await this.ready;
        const plugin = this.requirePlugin(pluginId);
        if (!plugin.frontendEntrypoint) {
            throw new Error(`Plugin "${pluginId}" declares no frontend entrypoint.`);
        }
        // `frontendEntrypoint` was resolved during discovery and validated to be
        // an existing file inside the plugin folder.
        return fs.readFile(plugin.frontendEntrypoint, 'utf8');
    }

    async getSnapshot(): Promise<PluginHostSnapshot> {
        await this.ready;
        return this.snapshot();
    }

    async refresh(): Promise<PluginHostSnapshot> {
        await this.ready;
        await this.rescan();
        await this.activateEnabledBackendPlugins();
        return this.snapshot();
    }

    async setTrusted(pluginId: string, trusted: boolean): Promise<PluginHostSnapshot> {
        await this.ready;
        const plugin = this.requirePlugin(pluginId);
        if (!isUserPluginPath(plugin.directory)) {
            throw new Error(`Built-in plugin "${pluginId}" is trusted by definition.`);
        }
        this.state.setTrusted(pluginId, trusted);
        if (!trusted) {
            // Revoking trust must also stop the plugin immediately.
            this.state.setEnabled(pluginId, false);
            await this.runtime.unload(pluginId);
        }
        return this.snapshot();
    }

    async setEnabled(pluginId: string, enabled: boolean): Promise<PluginHostSnapshot> {
        await this.ready;
        const plugin = this.requirePlugin(pluginId);
        if (enabled && !this.isTrusted(pluginId)) {
            throw new Error(
                `Plugin "${pluginId}" is third-party code with full system access. Accept the trust warning before enabling it.`
            );
        }
        this.state.setEnabled(pluginId, enabled);
        if (enabled) {
            await this.runtime.load(plugin);
        } else {
            await this.runtime.unload(pluginId);
        }
        return this.snapshot();
    }

    async reportError(pluginId: string, message: string): Promise<void> {
        this.logger.error(`[plugin-host] "${pluginId}" reported an error: ${message}`);
    }

    protected snapshot(): PluginHostSnapshot {
        return {
            plugins: this.discovered.map(toDescriptor),
            trusted: this.discovered.filter(plugin => this.isTrusted(plugin.manifest.id)).map(p => p.manifest.id),
            enabled: this.discovered.filter(plugin => this.isEnabled(plugin)).map(p => p.manifest.id),
            diagnostics: this.diagnostics
        };
    }

    /**
     * Built-in plugins start enabled: they ship with BruceDE and the user can
     * still disable them. Third-party plugins stay off until the user accepts
     * the full-system-access warning and opts in.
     */
    protected isEnabled(plugin: DiscoveredPlugin): boolean {
        const override = this.state.enabledOverride(plugin.manifest.id);
        if (override !== undefined) {
            return override;
        }
        return !isUserPluginPath(plugin.directory);
    }

    protected isTrusted(pluginId: string): boolean {
        const plugin = this.discovered.find(candidate => candidate.manifest.id === pluginId);
        if (!plugin) {
            return false;
        }
        // Built-in plugins ship with BruceDE; only third-party code needs a
        // user decision.
        return !isUserPluginPath(plugin.directory) || this.state.isTrusted(pluginId);
    }

    protected async rescan(): Promise<void> {
        const result = await discoverPlugins(this.roots);
        this.discovered = result.plugins;
        this.diagnostics = result.diagnostics;
        const knownIds = this.discovered.map(plugin => plugin.manifest.id);
        await this.state.load(knownIds);
        this.state.prune(knownIds);
        for (const diagnostic of this.diagnostics) {
            this.logger.warn(`[plugin-host] ${diagnostic.message} (${diagnostic.directory})`);
        }
    }

    protected async activateEnabledBackendPlugins(): Promise<void> {
        for (const plugin of this.discovered) {
            if (!this.isEnabled(plugin) || !this.isTrusted(plugin.manifest.id)) {
                continue;
            }
            await this.runtime.load(plugin);
        }
    }

    protected requirePlugin(pluginId: string): DiscoveredPlugin {
        const plugin = this.discovered.find(candidate => candidate.manifest.id === pluginId);
        if (!plugin) {
            throw new Error(`Unknown plugin: ${pluginId}`);
        }
        return plugin;
    }

    protected async serveAsset(request: express.Request, response: express.Response): Promise<void> {
        const pluginId = decodeURIComponent(String(request.params.pluginId ?? ''));
        const plugin = this.discovered.find(candidate => candidate.manifest.id === pluginId);
        if (!plugin) {
            response.status(404).type('text/plain').send(`Unknown plugin: ${pluginId}`);
            return;
        }
        // Inside `app.use(<mount>, handler)` Express rewrites `request.url` to the
        // part after the mount path; `params[0]` only exists for an explicit
        // wildcard segment, so read the remainder from the URL instead.
        const relative = safeDecode(request.url.split('?')[0] ?? '').replace(/^\/+/, '');
        if (!relative) {
            response.status(404).type('text/plain').send('Missing asset path.');
            return;
        }
        const absolute = path.resolve(plugin.directory, relative);
        const within = path.relative(plugin.directory, absolute);
        if (within.startsWith('..') || path.isAbsolute(within)) {
            response.status(403).type('text/plain').send('Asset path escapes the plugin folder.');
            return;
        }
        try {
            const stats = await fs.stat(absolute);
            if (!stats.isFile()) {
                throw new Error('not a file');
            }
            response.type(CONTENT_TYPES[path.extname(absolute).toLowerCase()] ?? 'application/octet-stream');
            response.setHeader('Cache-Control', 'no-cache');
            await new Promise<void>((resolve, reject) => {
                response.sendFile(absolute, error => (error ? reject(error) : resolve()));
            });
        } catch {
            response.status(404).type('text/plain').send(`Asset not found: ${relative}`);
        }
    }
}

/** `decodeURIComponent` that never throws on malformed input. */
function safeDecode(value: string): string {
    try {
        return decodeURIComponent(value);
    } catch {
        return value;
    }
}
